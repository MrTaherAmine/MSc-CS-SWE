import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDirectory = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDirectory, '..');
const checks = [];

function check(label, condition) {
  checks.push({ label, passed: Boolean(condition) });
}

function read(relativePath) {
  return readFileSync(path.join(projectRoot, relativePath), 'utf8');
}

const blueprint = read('render.yaml');
const clientApi = read('client/src/services/api.js');
const serverApp = read('server/src/app.js');
const authUtilities = read('server/src/utils/auth.js');
const rootPackage = JSON.parse(read('package.json'));

check('production client build exists', existsSync(path.join(projectRoot, 'client/dist/index.html')));
check('Render Blueprint defines a Node web service', /type:\s*web[\s\S]*runtime:\s*node/.test(blueprint));
check('Render health check targets /api/health', /healthCheckPath:\s*\/api\/health/.test(blueprint));
check('MongoDB URI is prompted as a secret', /key:\s*MONGODB_URI\s*\n\s*sync:\s*false/.test(blueprint));
check('JWT secret is generated by Render', /key:\s*JWT_SECRET\s*\n\s*generateValue:\s*true/.test(blueprint));
check('client defaults to same-origin API', /VITE_API_URL\s*\|\|\s*['"]\/api['"]/.test(clientApi));
check('server serves the production React build', /express\.static\(clientDistPath/.test(serverApp));
check('root start script launches the API server', rootPackage.scripts?.start === 'npm start --prefix server');
check('production cookies are HTTP-only and secure', /httpOnly:\s*true/.test(authUtilities) && /secure:\s*process\.env\.NODE_ENV\s*===\s*['"]production['"]/.test(authUtilities));
check('security policy allows Open Library covers', /img-src 'self' data: https:\/\/covers\.openlibrary\.org/.test(serverApp));

const trackedFiles = execFileSync('git', ['ls-files'], {
  cwd: projectRoot,
  encoding: 'utf8'
}).trim().split('\n');

check('no local environment secret file is tracked', !trackedFiles.some(file => [
  '.env',
  '.env.local',
  'server/.env',
  'client/.env'
].includes(file)));

process.env.NODE_ENV = 'production';
const { default: app } = await import('../server/src/app.js');
const server = await new Promise(resolve => {
  const listeningServer = app.listen(0, '127.0.0.1', () => resolve(listeningServer));
});

try {
  const address = server.address();
  const baseUrl = `http://127.0.0.1:${address.port}`;
  const homeResponse = await fetch(`${baseUrl}/`, {
    headers: { Accept: 'text/html' }
  });
  const homeHtml = await homeResponse.text();
  const routeResponse = await fetch(`${baseUrl}/search`, {
    headers: { Accept: 'text/html' }
  });
  const healthResponse = await fetch(`${baseUrl}/api/health`);
  const health = await healthResponse.json();
  const sameOriginResponse = await fetch(`${baseUrl}/api/health`, {
    headers: { Origin: baseUrl }
  });
  const foreignOriginResponse = await fetch(`${baseUrl}/api/health`, {
    headers: { Origin: 'https://untrusted.example' }
  });

  check('production server returns the React application', homeResponse.status === 200 && homeHtml.includes('BookSphere'));
  check('SPA routes fall back to the React application', routeResponse.status === 200);
  check('health endpoint reports an unavailable database', healthResponse.status === 503 && health.database === 'disconnected');
  check('production security headers are present', homeResponse.headers.get('x-content-type-options') === 'nosniff');
  check('same-origin credential requests are allowed', sameOriginResponse.headers.get('access-control-allow-origin') === baseUrl);
  check('unknown browser origins are not authorized', foreignOriginResponse.headers.get('access-control-allow-origin') === null);
} finally {
  await new Promise((resolve, reject) => {
    server.close(error => error ? reject(error) : resolve());
  });
}

for (const result of checks) {
  console.log(`${result.passed ? '✓' : '✗'} ${result.label}`);
}

const failed = checks.filter(result => !result.passed);

if (failed.length > 0) {
  console.error(`\n${failed.length} deployment check(s) failed.`);
  process.exit(1);
}

console.log(`\nDeployment verification passed (${checks.length}/${checks.length}).`);
